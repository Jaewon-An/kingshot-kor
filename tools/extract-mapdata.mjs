// Regenerates ../mapdata.js from the MIT-licensed Alliance-Layout-Planner
// (https://github.com/Bleezy-D/Alliance-Layout-Planner), whose map layers were
// extracted from the community ksmapper dataset (https://ksmapper.pages.dev/).
//
// Usage: node tools/extract-mapdata.mjs [path-or-url-to-index.html]
import { readFile, writeFile } from 'node:fs/promises';
import { inflateRawSync, inflateSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const SRC = process.argv[2] || 'https://raw.githubusercontent.com/Bleezy-D/Alliance-Layout-Planner/main/index.html';
const OUT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'mapdata.js');

const html = SRC.startsWith('http') ? await (await fetch(SRC)).text() : await readFile(SRC, 'utf8');

function grab(name) {
  const m = new RegExp(`const ${name}\\s*=\\s*([\\s\\S]*?);[ \\t]*(?:\\/\\/[^\\n]*)?\\n`).exec(html);
  if (!m) throw new Error(`${name} not found in source`);
  return m[1].trim();
}

const structRaw = grab('PERM_STRUCT');
const castleRaw = grab('CASTLE_STRUCT').replace(/\/\/.*$/gm, '');
const zonesRaw = grab('ZONES').replace(/\/\/.*$/gm, '');
const kingRaw = grab('KING_ZONE').replace(/\/\/.*$/gm, '');
const nodesB64 = eval(grab('NODES_B64'));
const terrainB64 = eval(grab('TERRAIN_B64'));

// Sanity-check the payloads decode to what the app expects.
const unzip = b => {
  const buf = Buffer.from(b, 'base64');
  const isZlib = (buf[0] & 15) === 8 && (buf[0] * 256 + buf[1]) % 31 === 0;
  return isZlib ? inflateSync(buf) : inflateRawSync(buf);
};
const terrain = unzip(terrainB64);
const nodes = unzip(nodesB64);
if (terrain.length !== 1200 * 300) throw new Error(`terrain: unexpected size ${terrain.length}`);
if (nodes.length % 3) throw new Error(`nodes: unexpected size ${nodes.length}`);
const structs = eval(structRaw);

const out = `/* Kingshot real map layers — generated by tools/extract-mapdata.mjs, do not edit.
 * Source: Alliance-Layout-Planner (MIT) https://github.com/Bleezy-D/Alliance-Layout-Planner
 *         data originally from the community ksmapper dataset https://ksmapper.pages.dev/
 *
 * Coordinates in STRUCTS / CASTLE / ZONES / KING_ZONE are GAME coordinates (X, Y);
 * a footprint [gx, gy, size] covers game tiles gx..gx+size-1 × gy..gy+size-1.
 * TERRAIN_B64: zlib, 1200 rows × 300 bytes, 2 bits per tile (1 = mountain, 2 = lake),
 *   row index iy, column ix  ->  game X = ix, game Y = 1199 - iy.
 * NODES_B64: zlib, 3-byte records v: type = (v>>22)&3 (bread/wood/stone/iron),
 *   ix = (v>>11)&2047, iy = v&2047; 2×2 node covering ix..ix+1, iy..iy+1 (same frame as terrain).
 * ${structs.length} structures, ${nodes.length / 3} resource nodes.
 */
window.KS_MAPDATA = {
  KING_ZONE: ${kingRaw},
  ZONES: ${zonesRaw},
  /* [label, letter, gx, gy, size, color] */
  CASTLE: ${castleRaw},
  /* [gx, gy, size, noBuildZoneSize, cityExempt, letter, color, category, in-game name] */
  STRUCTS: ${structRaw},
  NODES_B64: '${nodesB64}',
  TERRAIN_B64: '${terrainB64}'
};
`;
await writeFile(OUT, out);
console.log(`wrote ${OUT}: ${structs.length} structures, ${nodes.length / 3} nodes`);
